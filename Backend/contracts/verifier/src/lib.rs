// Data Types
// ─────────────────────────────────────────────────────────────────────────────

/// Groth16 Verification Key produced by the trusted setup (arkworks).
///
/// Byte sizes follow the BLS12-381 uncompressed encoding documented above.
/// Set once at deployment via `initialize()`.
#[contracttype]
#[derive(Clone)]
pub struct VerificationKey {
    /// [α]_1 — Alpha point on G1 (96 bytes)
    pub alpha_g1: BytesN<96>,
    /// [β]_2 — Beta point on G2 (192 bytes)
    pub beta_g2: BytesN<192>,
    /// [γ]_2 — Gamma point on G2 (192 bytes)
    pub gamma_g2: BytesN<192>,
    /// [δ]_2 — Delta point on G2 (192 bytes)
    pub delta_g2: BytesN<192>,
    /// Input Commitments [IC_0, IC_1, IC_2, IC_3], each a G1 point (96 bytes):
    ///   IC_0 — constant term
    ///   IC_1 — coefficient for `threshold`
    ///   IC_2 — coefficient for `asset_id`
    ///   IC_3 — coefficient for `nonce`
    pub ic: Vec<BytesN<96>>,
}

/// A Groth16 proof (π) over BLS12-381.
#[contracttype]
#[derive(Clone)]
pub struct Proof {
    /// π_A ∈ G1 (96 bytes)
    pub a: BytesN<96>,
    /// π_B ∈ G2 (192 bytes)
    pub b: BytesN<192>,
    /// π_C ∈ G1 (96 bytes)
    pub c: BytesN<96>,
}

/// Public inputs bound to the proof. Each is a 32-byte big-endian Fr scalar.
#[contracttype]
#[derive(Clone)]
pub struct PublicInputs {
    /// Minimum balance threshold (e.g. $5,000 USDC = 5_000_000_000)
    pub threshold: BytesN<32>,
    /// Asset identifier — field-element hash of the asset code (e.g. "USDC")
    pub asset_id: BytesN<32>,
    /// Unique random nonce — prevents the same proof from being accepted twice
    pub nonce: BytesN<32>,
}

/// Contract storage keys.
#[contracttype]
pub enum StorageKey {
    Admin,
    VerificationKey,
    /// Tracks which nonces have already been used (replay protection)
    UsedNonce(BytesN<32>),
}

// ─────────────────────────────────────────────────────────────────────────────
// Contract
// ─────────────────────────────────────────────────────────────────────────────

#[contract]
pub struct ZkCredVerifier;

#[contractimpl]
impl ZkCredVerifier {
    // ── Admin Functions ───────────────────────────────────────────────────────

    /// Initialize the contract with the Verification Key from the trusted setup.
    /// Call once immediately after deployment.
    pub fn initialize(env: Env, admin: Address, vk: VerificationKey) {
        if env.storage().instance().has(&StorageKey::Admin) {
            panic!("Contract is already initialized");
        }
        admin.require_auth();
        if vk.ic.len() != 4 {
            panic!("VK must contain exactly 4 IC points (1 constant + 3 public inputs)");
        }
        env.storage().instance().set(&StorageKey::Admin, &admin);
        env.storage()
            .instance()
            .set(&StorageKey::VerificationKey, &vk);
        env.storage().instance().extend_ttl(100_000, 100_000);
    }

    /// Replace the Verification Key. Admin-only. Required if the circuit changes.
    pub fn update_vk(env: Env, vk: VerificationKey) {
        let admin: Address = env
            .storage()
            .instance()
            .get(&StorageKey::Admin)
            .expect("Not initialized");
        admin.require_auth();
        if vk.ic.len() != 4 {
            panic!("VK must contain exactly 4 IC points");
        }
        env.storage()
            .instance()
            .set(&StorageKey::VerificationKey, &vk);
    }

    // ── Core Verification Function ────────────────────────────────────────────

    /// Verify a zkCred zero-knowledge proof on-chain via BLS12-381 host
    /// functions. Returns `true` iff the proof is valid for the given public
    /// inputs AND the nonce has not been previously consumed.
    pub fn verify_proof(env: Env, proof: Proof, inputs: PublicInputs) -> bool {
        // ── Step 0: Replay protection ─────────────────────────────────────────
        let nonce_key = StorageKey::UsedNonce(inputs.nonce.clone());
        if env.storage().temporary().has(&nonce_key) {
            return false; // Proof already consumed
        }

        let vk: VerificationKey = env
            .storage()
            .instance()
            .get(&StorageKey::VerificationKey)
            .expect("Call initialize() before verify_proof()");

        let bls = env.crypto().bls12_381();

        // ── Step 1: Prepared public input vk_x ────────────────────────────────
        //
        //   vk_x = IC[0] + threshold·IC[1] + asset_id·IC[2] + nonce·IC[3]
        //
        // Computed as an MSM over the three variable IC points, then added to
        // the constant term IC[0].
        let ic0 = G1Affine::from_bytes(vk.ic.get(0).unwrap());
        let ic1 = G1Affine::from_bytes(vk.ic.get(1).unwrap());
        let ic2 = G1Affine::from_bytes(vk.ic.get(2).unwrap());
        let ic3 = G1Affine::from_bytes(vk.ic.get(3).unwrap());

        let mut msm_points: Vec<G1Affine> = Vec::new(&env);
        msm_points.push_back(ic1);
        msm_points.push_back(ic2);
        msm_points.push_back(ic3);

        let mut msm_scalars: Vec<Fr> = Vec::new(&env);
        msm_scalars.push_back(Fr::from_bytes(inputs.threshold));
        msm_scalars.push_back(Fr::from_bytes(inputs.asset_id));
        msm_scalars.push_back(Fr::from_bytes(inputs.nonce));

        let acc = bls.g1_msm(msm_points, msm_scalars);
        let vk_x = bls.g1_add(&ic0, &acc);

        // ── Step 2: Groth16 pairing check ─────────────────────────────────────
        //
        //   e(A, B) · e(−α, β) · e(−vk_x, γ) · e(−C, δ) == 1
        let a = G1Affine::from_bytes(proof.a);
        let c = G1Affine::from_bytes(proof.c);

        let neg_alpha = negate_g1(&env, &vk.alpha_g1);
        let neg_vk_x = negate_g1(&env, &vk_x.to_bytes());
        let neg_c = negate_g1(&env, &c.to_bytes());

        let mut vp1: Vec<G1Affine> = Vec::new(&env);
        vp1.push_back(a); //  A
        vp1.push_back(neg_alpha); // −α
        vp1.push_back(neg_vk_x); // −vk_x
        vp1.push_back(neg_c); // −C

        let mut vp2: Vec<G2Affine> = Vec::new(&env);
        vp2.push_back(G2Affine::from_bytes(proof.b)); //  B
        vp2.push_back(G2Affine::from_bytes(vk.beta_g2)); //  β
        vp2.push_back(G2Affine::from_bytes(vk.gamma_g2)); //  γ
        vp2.push_back(G2Affine::from_bytes(vk.delta_g2)); //  δ

        let is_valid = bls.pairing_check(vp1, vp2);

        // ── Step 3: Record nonce to block replay ──────────────────────────────
        if is_valid {
            // TTL ≈ 150 days at 5s/ledger
            env.storage().temporary().set(&nonce_key, &true);
            env.storage()
                .temporary()
                .extend_ttl(&nonce_key, 2_592_000, 2_592_000);
        }

        is_valid
    }

    // ── Read-Only Functions ───────────────────────────────────────────────────

    pub fn get_vk(env: Env) -> VerificationKey {
        env.storage()
            .instance()
            .get(&StorageKey::VerificationKey)
            .expect("Not initialized")
    }

    pub fn get_admin(env: Env) -> Address {
        env.storage()
            .instance()
            .get(&StorageKey::Admin)
            .expect("Not initialized")
    }

    pub fn is_nonce_used(env: Env, nonce: BytesN<32>) -> bool {
        env.storage()
            .temporary()
            .has(&StorageKey::UsedNonce(nonce))
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// Internal Helpers
// ─────────────────────────────────────────────────────────────────────────────

/// Negate a BLS12-381 G1 point: (x, y) → (x, p − y).
///
/// G1 is 96 bytes: be(x)[0..48] || be(y)[48..96]. The point at infinity is
/// encoded as all-zero bytes and negates to itself.
fn negate_g1(env: &Env, point: &BytesN<96>) -> G1Affine {
    let p = point.to_array();

    // Point at infinity (all zero) negates to itself.
    let mut all_zero = true;
    for b in p.iter() {
        if *b != 0 {
            all_zero = false;
            break;
        }
    }
    if all_zero {
        return G1Affine::from_bytes(BytesN::from_array(env, &p));
    }

    let mut x = [0u8; 48];
    let mut y = [0u8; 48];
    x.copy_from_slice(&p[0..48]);
    y.copy_from_slice(&p[48..96]);

    // neg_y = p − y  (big-endian subtraction, 0 <= y < p)
    let neg_y = be_sub_48(&BLS12_381_FP_MODULUS_BE, &y);

    let mut result = [0u8; 96];
    result[0..48].copy_from_slice(&x);
    result[48..96].copy_from_slice(&neg_y);

    G1Affine::from_bytes(BytesN::from_array(env, &result))
}

/// Big-endian 48-byte subtraction: a − b (assumes a >= b).
fn be_sub_48(a: &[u8; 48], b: &[u8; 48]) -> [u8; 48] {
    let mut result = [0u8; 48];
    let mut borrow: i16 = 0;
    for i in (0..48).rev() {
        let diff = a[i] as i16 - b[i] as i16 - borrow;
        if diff < 0 {
            result[i] = (diff + 256) as u8;
            borrow = 1;
        } else {
            result[i] = diff as u8;
            borrow = 0;
        }
    }
    result
}

