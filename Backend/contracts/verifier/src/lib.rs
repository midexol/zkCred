#[cfg(test)]
mod tests {
    use super::*;
    use soroban_sdk::{testutils::Address as _, Bytes};

    fn zeros<const N: usize>(env: &Env) -> BytesN<N> {
        BytesN::from_array(env, &[0u8; N])
    }

    fn dummy_vk(env: &Env) -> VerificationKey {
        let mut ic = Vec::new(env);
        for _ in 0..4 {
            ic.push_back(zeros::<96>(env));
        }
        VerificationKey {
            alpha_g1: zeros::<96>(env),
            beta_g2: zeros::<192>(env),
            gamma_g2: zeros::<192>(env),
            delta_g2: zeros::<192>(env),
            ic,
        }
    }

    #[test]
    fn test_initialize_and_get_vk() {
        let env = Env::default();
        env.mock_all_auths();
        let contract_id = env.register_contract(None, ZkCredVerifier);
        let client = ZkCredVerifierClient::new(&env, &contract_id);

        let admin = Address::generate(&env);
        client.initialize(&admin, &dummy_vk(&env));
        assert_eq!(client.get_admin(), admin);
        assert_eq!(client.get_vk().ic.len(), 4);
    }

    #[test]
    #[should_panic(expected = "already initialized")]
    fn test_double_initialize_panics() {
        let env = Env::default();
        env.mock_all_auths();
        let contract_id = env.register_contract(None, ZkCredVerifier);
        let client = ZkCredVerifierClient::new(&env, &contract_id);
        let admin = Address::generate(&env);
        client.initialize(&admin, &dummy_vk(&env));
        client.initialize(&admin, &dummy_vk(&env));
    }

    #[test]
    fn test_nonce_not_recorded_on_failed_proof() {
        let env = Env::default();
        env.mock_all_auths();
        let contract_id = env.register_contract(None, ZkCredVerifier);
        let client = ZkCredVerifierClient::new(&env, &contract_id);

        let admin = Address::generate(&env);
        client.initialize(&admin, &dummy_vk(&env));

        let proof = Proof {
            a: zeros::<96>(&env),
            b: zeros::<192>(&env),
            c: zeros::<96>(&env),
        };
        let nonce = BytesN::from_array(&env, &[0xAB; 32]);
        let inputs = PublicInputs {
            threshold: zeros::<32>(&env),
            asset_id: zeros::<32>(&env),
            nonce: nonce.clone(),
        };

        // All-zero (infinity) points will not satisfy the pairing equation.
        let result = client.verify_proof(&proof, &inputs);
        assert!(!result, "Dummy proof must not verify");
        assert!(!client.is_nonce_used(&nonce), "Nonce must not be recorded on failure");
    }

    #[test]
    fn test_negate_g1_infinity_is_identity() {
        let env = Env::default();
        let inf = zeros::<96>(&env);
        let neg = negate_g1(&env, &inf);
        assert_eq!(neg.to_bytes(), inf);
    }

    #[test]
    fn test_be_sub_48_basic() {
        let mut a = [0u8; 48];
        let mut b = [0u8; 48];
        a[47] = 5;
        b[47] = 3;
        let r = be_sub_48(&a, &b);
        assert_eq!(r[47], 2);
        // borrow propagation
        let mut a2 = [0u8; 48];
        a2[46] = 1; // value = 256
        let mut b2 = [0u8; 48];
        b2[47] = 1; // value = 1
        let r2 = be_sub_48(&a2, &b2); // 256 - 1 = 255
        assert_eq!(r2[47], 0xff);
        assert_eq!(r2[46], 0x00);
    }

    // Silence unused import warning when bls path is exercised only on-chain.
    #[allow(dead_code)]
    fn _bytes_marker(env: &Env) -> Bytes {
        Bytes::new(env)
    }
}
