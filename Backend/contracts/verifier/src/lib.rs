//! zkCred — On-Chain Groth16 Verifier (Soroban Smart Contract)
//!
//! This contract lives on the Stellar network (Testnet → Mainnet) and serves
//! as the *single source of truth* for proof verification.
//!
//! ## Curve choice — BLS12-381 (the refit)
//!
//! Stellar's released protocol exposes **BLS12-381** cryptographic host
//! functions (`env.crypto().bls12_381()`), NOT BN254. The proving pipeline is
//! therefore arkworks `ark-groth16` over `ark-bls12-381`, which emits proofs
//! and a verification key in the BLS12-381 groups. All three layers — circuit,
//! prover, and this verifier — now speak the same cryptographic language.
//!
//! ## What it does
//! 1. Stores the Groth16 Verification Key (VK) generated by the trusted setup.
//! 2. Exposes `verify_proof()`, which uses BLS12-381 host functions to run an
//!    on-chain pairing check.
//! 3. Returns `true` iff the proof is valid AND the nonce is fresh.
//!
//! ## Groth16 Verification Equation
//!
//!   e(A, B) == e(α, β) · e(vk_x, γ) · e(C, δ)
//!
//! Re-arranged into product-of-pairings-equals-one form (what `pairing_check`
//! evaluates):
//!
//!   e(A, B) · e(−α, β) · e(−vk_x, γ) · e(−C, δ) == 1
//!
//! Where `vk_x = IC[0] + threshold·IC[1] + asset_id·IC[2] + nonce·IC[3]`.
//!
//! ## Serialization (must match the arkworks adapter in the prover)
//!   G1 point  = 96 bytes  : be(x) || be(y),   each Fp is 48 BE bytes
//!   G2 point  = 192 bytes : be(x_c1)||be(x_c0)||be(y_c1)||be(y_c0)
//!   Scalar Fr = 32 bytes  : big-endian, reduced mod r
//!   Infinity  = all-zero bytes

#![no_std]

use soroban_sdk::{
    contract, contractimpl, contracttype,
    crypto::bls12_381::{Fr, G1Affine, G2Affine},
    Address, BytesN, Env, Vec,
};

// BLS12-381 base field modulus p, big-endian, 48 bytes.
// p = 0x1a0111ea397fe69a4b1ba7b6434bacd764774b84f38512bf6730d2a0f6b0f624
//       1eabfffeb153ffffb9feffffffffaaab
const BLS12_381_FP_MODULUS_BE: [u8; 48] = [
    0x1a, 0x01, 0x11, 0xea, 0x39, 0x7f, 0xe6, 0x9a, 0x4b, 0x1b, 0xa7, 0xb6, 0x43, 0x4b, 0xac, 0xd7,
    0x64, 0x77, 0x4b, 0x84, 0xf3, 0x85, 0x12, 0xbf, 0x67, 0x30, 0xd2, 0xa0, 0xf6, 0xb0, 0xf6, 0x24,
    0x1e, 0xab, 0xff, 0xfe, 0xb1, 0x53, 0xff, 0xff, 0xb9, 0xfe, 0xff, 0xff, 0xff, 0xff, 0xaa, 0xab,
];

